//! Per-service log ingestion for persistence, crash sampling and best-effort UI display.

use crate::{LogBatch, ServiceId};
use std::{
    collections::VecDeque,
    future::Future,
    sync::Arc,
    time::{Duration, SystemTime},
};
use thiserror::Error;
use tokio::{
    sync::{mpsc, oneshot},
    time::{sleep_until, Instant},
};

const RING_LINES: usize = 5_000;
const BATCH_LINES: usize = 100;
const BATCH_DELAY: Duration = Duration::from_millis(16);

/// Stream on which the runtime observed a line.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LogSource {
    /// Service standard output.
    Stdout,
    /// Service standard error.
    Stderr,
    /// Message generated by the runtime.
    System,
}

/// One already-redacted record. The adapter must redact before submitting a record.
/// The same immutable body is shared by persistence and crash samples.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LogEntry {
    /// Originating stream.
    pub source: LogSource,
    /// Original observation time, independent of ingestion order.
    pub timestamp: SystemTime,
    /// Sanitized text without its line terminator.
    pub redacted_body: Arc<str>,
}

/// A bounded history for one service. The default capacity is 5,000 records.
pub struct LogRing {
    entries: VecDeque<LogEntry>,
    capacity: usize,
}

impl Default for LogRing {
    fn default() -> Self {
        Self::new(RING_LINES)
    }
}

impl LogRing {
    /// Create a history retaining at most `capacity` records.
    pub fn new(capacity: usize) -> Self {
        Self {
            entries: VecDeque::new(),
            capacity,
        }
    }

    /// Append in ingestion order, evicting the oldest record when full.
    pub fn push(&mut self, entry: LogEntry) {
        if self.capacity == 0 {
            return;
        }
        if self.entries.len() == self.capacity {
            self.entries.pop_front();
        }
        self.entries.push_back(entry);
    }

    /// Sample up to the last `count` records, oldest first, without consuming them.
    pub fn tail(&self, count: usize) -> Vec<LogEntry> {
        let start = self.entries.len().saturating_sub(count);
        self.entries.range(start..).cloned().collect()
    }
}

/// Ordered input to one service's collector. A sample includes every preceding record
/// on this queue, including records still waiting to form a UI batch.
pub enum LogInput {
    /// An adapter-redacted record for the service.
    Line(LogEntry),
    /// Request a point-in-time crash sample while ingestion is running.
    Tail {
        /// Maximum number of recent records to return.
        count: usize,
        /// Receives the sample in ingestion order.
        reply: oneshot::Sender<Vec<LogEntry>>,
    },
}

/// A failure of the full-fidelity log path.
#[derive(Debug, Error)]
pub enum LogError {
    /// The persistence consumer closed before accepting a record.
    #[error("complete log stream closed")]
    CompleteStreamClosed,
}

/// Collector for a single service. Run one per service with a dedicated persistence
/// stream and the workspace's shared UI sender.
pub struct LogIngestor {
    complete: mpsc::Sender<LogEntry>,
    ui: UiBatches,
}

impl LogIngestor {
    /// Bind both outputs. The complete stream applies backpressure to this service.
    pub fn new(
        service_id: ServiceId,
        complete: mpsc::Sender<LogEntry>,
        ui: mpsc::Sender<LogBatch>,
    ) -> Self {
        Self {
            complete,
            ui: UiBatches {
                service_id,
                sender: ui,
                lines: Vec::new(),
                deadline: None,
                dropped_count: 0,
            },
        }
    }

    /// Forward every record to persistence and history before offering it to the UI.
    /// Closing all input senders drains queued records, flushes the tail batch and
    /// returns the final crash history. A closed UI leaves persistence running.
    pub async fn run(mut self, mut input: mpsc::Receiver<LogInput>) -> Result<LogRing, LogError> {
        let mut ring = LogRing::default();
        while let Some(message) = self.ui.wait(input.recv()).await {
            match message {
                LogInput::Line(entry) => {
                    if self
                        .ui
                        .wait(self.complete.send(entry.clone()))
                        .await
                        .is_err()
                    {
                        self.ui.flush();
                        return Err(LogError::CompleteStreamClosed);
                    }
                    let body = Arc::clone(&entry.redacted_body);
                    ring.push(entry);
                    self.ui.push(&body);
                }
                LogInput::Tail { count, reply } => {
                    let _ = reply.send(ring.tail(count));
                }
            }
        }
        self.ui.flush();
        Ok(ring)
    }
}

struct UiBatches {
    service_id: ServiceId,
    sender: mpsc::Sender<LogBatch>,
    lines: Vec<String>,
    deadline: Option<Instant>,
    dropped_count: usize,
}

impl UiBatches {
    // Keep the first pending line's deadline live while waiting for either input or
    // persistence capacity. An idle collector with no pending lines needs no timer.
    async fn wait<T>(&mut self, operation: impl Future<Output = T>) -> T {
        tokio::pin!(operation);
        if let Some(deadline) = self.deadline {
            tokio::select! {
                biased;
                _ = sleep_until(deadline) => self.flush(),
                result = &mut operation => return result,
            }
        }
        operation.await
    }

    fn push(&mut self, body: &str) {
        if self.lines.is_empty() {
            self.deadline = Some(Instant::now() + BATCH_DELAY);
        }
        self.lines.push(body.to_owned());
        if self.lines.len() == BATCH_LINES {
            self.flush();
        }
    }

    fn flush(&mut self) {
        self.deadline = None;
        let count = self.lines.len();
        if count == 0 && self.dropped_count == 0 {
            return;
        }
        let mut lines = std::mem::take(&mut self.lines);
        if self.dropped_count > 0 {
            lines.push(format!(
                "[WARN: {} lines omitted in TUI due to high output rate, see log file]",
                self.dropped_count
            ));
        }
        let batch = LogBatch {
            service_id: self.service_id.clone(),
            lines,
        };
        match self.sender.try_send(batch) {
            Ok(()) | Err(mpsc::error::TrySendError::Closed(_)) => self.dropped_count = 0,
            Err(mpsc::error::TrySendError::Full(_)) => {
                self.dropped_count = self.dropped_count.saturating_add(count);
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tokio::{sync::mpsc::error::TryRecvError, task::JoinHandle, time::advance};

    fn entry(index: u32) -> LogEntry {
        let source = match index % 3 {
            0 => LogSource::Stdout,
            1 => LogSource::Stderr,
            _ => LogSource::System,
        };
        LogEntry {
            source,
            // Simulate a clock stepping backwards. Input order remains authoritative.
            timestamp: SystemTime::UNIX_EPOCH + Duration::from_secs(u64::from(u32::MAX - index)),
            redacted_body: format!("record {index} [REDACTED]").into(),
        }
    }

    #[test]
    fn ring_evicts_oldest_at_5001_and_samples_in_arrival_order() {
        let mut ring = LogRing::default();
        for i in 1..=5_001 {
            ring.push(entry(i));
        }
        assert_eq!(
            ring.tail(usize::MAX),
            (2..=5_001).map(entry).collect::<Vec<_>>()
        );
        assert!(ring.tail(0).is_empty());
        assert_eq!(ring.tail(2), [entry(5_000), entry(5_001)]);
    }

    struct Collector {
        input: mpsc::Sender<LogInput>,
        full: mpsc::Receiver<LogEntry>,
        task: JoinHandle<Result<LogRing, LogError>>,
    }

    impl Collector {
        fn new(id: &str, ui: mpsc::Sender<LogBatch>, full_capacity: usize) -> Self {
            let (input, rx) = mpsc::channel(32);
            let (complete, full) = mpsc::channel(full_capacity);
            let ingestor = LogIngestor::new(id.to_owned(), complete, ui);
            Self {
                input,
                full,
                task: tokio::spawn(ingestor.run(rx)),
            }
        }

        async fn line(&self, index: u32) {
            self.input.send(LogInput::Line(entry(index))).await.unwrap();
        }

        async fn tail(&self, count: usize) -> Vec<LogEntry> {
            let (reply, sample) = oneshot::channel();
            self.input
                .send(LogInput::Tail { count, reply })
                .await
                .unwrap();
            sample.await.unwrap()
        }
    }

    fn assert_batch(batch: LogBatch, id: &str, indices: impl IntoIterator<Item = u32>) {
        assert_eq!(batch.service_id, id);
        let expected: Vec<_> = indices
            .into_iter()
            .map(|i| entry(i).redacted_body.to_string())
            .collect();
        assert_eq!(batch.lines, expected);
    }

    #[tokio::test(start_paused = true)]
    async fn hundred_lines_flush_early_and_service_deadlines_are_independent() {
        let (ui, mut batches) = mpsc::channel(4);
        let db = Collector::new("db", ui.clone(), 128);
        let api = Collector::new("api", ui, 128);
        let start = Instant::now();
        api.line(777).await;
        assert_eq!(api.tail(1).await, [entry(777)]);
        advance(Duration::from_millis(9)).await;
        for i in 0..99 {
            db.line(i).await;
        }
        assert_eq!(db.tail(1).await, [entry(98)]);
        assert!(matches!(batches.try_recv(), Err(TryRecvError::Empty)));
        db.line(99).await;
        db.tail(0).await;
        assert_batch(batches.try_recv().unwrap(), "db", 0..100);
        assert_eq!(Instant::now() - start, Duration::from_millis(9));

        db.line(100).await;
        assert_eq!(db.tail(1).await, [entry(100)]);
        api.line(778).await;
        api.tail(0).await;
        advance(Duration::from_millis(6)).await;
        api.tail(0).await;
        assert!(matches!(batches.try_recv(), Err(TryRecvError::Empty)));
        advance(Duration::from_millis(1)).await;
        api.tail(0).await;
        assert_batch(batches.try_recv().unwrap(), "api", [777, 778]);
        assert!(matches!(batches.try_recv(), Err(TryRecvError::Empty)));

        // Close db at t=16 ms, well before its second deadline at t=25 ms.
        drop(db.input);
        assert_eq!(db.task.await.unwrap().unwrap().tail(1), [entry(100)]);
        assert_batch(batches.try_recv().unwrap(), "db", [100]);
        drop(api.input);
        assert_eq!(
            api.task.await.unwrap().unwrap().tail(3),
            [entry(777), entry(778)]
        );
        assert!(batches.recv().await.is_none());
    }

    #[tokio::test(start_paused = true)]
    async fn ui_recovery_counts_only_omitted_records_and_preserves_full_stream() {
        let (ui, mut batches) = mpsc::channel(1);
        let mut db = Collector::new("db", ui, 512);
        for i in 0..307 {
            db.line(i).await;
        }
        // The first 100 filled the UI. Two further full batches were dropped.
        assert_eq!(db.tail(3).await, [entry(304), entry(305), entry(306)]);
        advance(BATCH_DELAY).await;
        db.tail(0).await; // The seven-line batch also encountered the full UI.
        assert_batch(batches.try_recv().unwrap(), "db", 0..100);
        db.line(307).await;
        db.tail(0).await;
        advance(BATCH_DELAY).await;
        db.tail(0).await;
        let recovered = batches.try_recv().unwrap();
        assert_eq!(recovered.service_id, "db");
        assert_eq!(
            recovered.lines,
            [
                "record 307 [REDACTED]",
                "[WARN: 207 lines omitted in TUI due to high output rate, see log file]",
            ]
        );

        db.line(308).await;
        drop(db.input);
        let expected: Vec<_> = (0..309).map(entry).collect();
        let ring = db.task.await.unwrap().unwrap();
        assert_eq!(ring.tail(usize::MAX), expected);
        assert_batch(batches.try_recv().unwrap(), "db", [308]);
        let mut written = Vec::new();
        while let Some(line) = db.full.recv().await {
            written.push(line);
        }
        assert_eq!(written, expected);
    }

    #[tokio::test(start_paused = true)]
    async fn waiting_for_persistence_capacity_still_flushes_pending_ui() {
        let (ui, mut batches) = mpsc::channel(1);
        let mut db = Collector::new("db", ui, 1);
        db.line(0).await;
        db.tail(0).await;
        db.line(1).await;
        // The writer still holds record 0. Record 1 cannot reach the UI yet.
        advance(BATCH_DELAY).await;
        assert_batch(batches.recv().await.unwrap(), "db", [0]);
        assert_eq!(db.full.recv().await.unwrap(), entry(0));
        drop(batches);
        drop(db.input);
        assert_eq!(
            db.task.await.unwrap().unwrap().tail(2),
            [entry(0), entry(1)]
        );
        assert_eq!(db.full.recv().await.unwrap(), entry(1));
        assert!(db.full.recv().await.is_none());
    }

    #[tokio::test(start_paused = true)]
    async fn closed_persistence_stream_reports_failure_before_ui_delivery() {
        let (ui, mut batches) = mpsc::channel(2);
        let db = Collector::new("db", ui, 1);
        db.line(0).await;
        db.tail(0).await;
        drop(db.full);
        db.input.send(LogInput::Line(entry(1))).await.unwrap();
        assert!(matches!(
            db.task.await.unwrap(),
            Err(LogError::CompleteStreamClosed)
        ));
        assert_batch(batches.recv().await.unwrap(), "db", [0]);
        assert!(batches.recv().await.is_none());
    }
}
